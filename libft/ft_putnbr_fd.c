#include "libft.h"

void	ft_putnbr_fd(int nb, int fd)
{
	char	unit;

	if (fd <= 0)
		return ;
	unit = 48 + nb % 10;
	if (nb == -2147483648)
	{
		ft_putstr_fd("-2147483648", fd);
		return ;
	}
	else if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		ft_putnbr_fd(-nb, fd);
	}
	else if (nb > 9)
	{
		ft_putnbr_fd(nb / 10, fd);
		ft_putchar_fd(unit, fd);
	}
	else
		ft_putchar_fd(unit, fd);
}
